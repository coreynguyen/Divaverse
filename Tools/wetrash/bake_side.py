#!/usr/bin/env python3
# Bakes the side-view (Spear Run) art into atlases + a data header.  bake_side.py <psd dir> <res dir> <header>
# Needs psd-tools, numpy, scipy, Pillow. colour atlas: 5x3 cells of 318x237; mask atlas: R bikini, G head/hair, B do-not-tint (spear, handle, grips).
import sys, numpy as np
from psd_tools import PSDImage
from PIL import Image
from scipy import ndimage
src, res, hdr = sys.argv[1:4]; CW, CH = 318, 237
def layers(name):
    p = PSDImage.open(f'{src}/{name}.psd'); out = {}
    for l in p:
        im = Image.new('RGBA', p.size, (0, 0, 0, 0)); t = l.topil()
        if t is not None and l.bbox[2] > l.bbox[0]: im.paste(t.convert('RGBA'), (l.bbox[0], l.bbox[1]))
        out[l.name.lower()] = np.array(im)
    return out
F, C, S, T, HP, EX, DT = (layers(n) for n in ('frames', 'clothes', 'sculpts', 'ties', 'handle_points', 'exhaust', 'donttint'))
ORDER = ['ani1', 'ani2', 'ani3', 'ani4', 'ani5', 'throw1', 'throw2', 'throw3', 'throw4', 'ski_body', 'ski_hull', 'ski_handle', 'ski_handle_grips', 'spear']
ENUM = ['SD_SIT', 'SD_A2', 'SD_A3', 'SD_A4', 'SD_TUCK', 'SD_T1', 'SD_T2', 'SD_T3', 'SD_T4', 'SD_BODY', 'SD_HULL', 'SD_HANDLE', 'SD_GRIPS', 'SD_SPEAR']
col = Image.new('RGBA', (CW * 5, CH * 3), (0, 0, 0, 0)); msk = Image.new('RGB', (CW * 5, CH * 3), (0, 0, 0)); rows = []
def ends(a):                       # the two ends of a drawn line mask (principal axis)
    ys, xs = np.nonzero(a)
    if len(xs) < 2: return (0, 0, 0, 0)
    p = np.stack([xs, ys], 1).astype(float); c = p.mean(0); u = np.linalg.svd(p - c)[2][0]; t = (p - c) @ u
    a0, a1 = c + u * t.min(), c + u * t.max()
    if a0[0] > a1[0]: a0, a1 = a1, a0
    return (a0[0], a0[1], a1[0], a1[1])
for i, n in enumerate(ORDER):
    f = F[n]; ox, oy = (i % 5) * CW, (i // 5) * CH; col.paste(Image.fromarray(f), (ox, oy))
    m = np.zeros((CH, CW, 3), np.uint8)
    if i < 9: m[..., 0] = (C[n][..., 3] > 0) * 255; m[..., 1] = (S[n][..., 3] > 0) * 255
    if n in DT: m[..., 2] = (DT[n][..., 3] > 0) * 255          # the tie points only feed the header; B carries the artist's do-not-tint mask
    msk.paste(Image.fromarray(m), (ox, oy))
    ys, xs = np.nonzero(f[..., 3]); bb = (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    head = (0, 0, 0); tie = [(0, 0)]; nt = 0
    if i < 9:
        s = S[n][..., 3] > 0; ys, xs = np.nonzero(s); head = (xs.mean(), ys.mean(), (xs.max() - xs.min()) / 2 + 1)
        t = T[n][..., 3] > 0; lab, k = ndimage.label(t); cs = ndimage.center_of_mass(t, lab, range(1, k + 1))[:4]; nt = len(cs); tie = [(c[1], c[0]) for c in cs] or tie
    grip = ends(HP[n][..., 3] > 0) if n in HP else (0, 0, 0, 0)
    rows.append('    { {%d, %d, %d, %d}, {%.1ff, %.1ff, %.1ff}, %d, { %s }, {%.1ff, %.1ff, %.1ff, %.1ff} },   // %s' % (*bb, *head, nt, ', '.join('{%.1ff, %.1ff}' % t for t in tie), *grip, ENUM[i]))
piv = ndimage.center_of_mass(HP['ski_body'][..., 3] > 0); ex = ndimage.center_of_mass(EX['ski_body'][..., 3] > 0)
col.save(f'{res}/side_atlas.png', optimize=True); msk.save(f'{res}/side_masks.png', optimize=True)
open(hdr, 'w').write('''// Generated by Tools/wetrash/bake_side.py from the artist's side-view PSD layers. Do not edit.
#pragma once
enum SdFrame { %s, SD_FRAMES };
constexpr int SD_CW = %d, SD_CH = %d;
// grip: the line the handlebar grip lies on (x0, y0, x1, y1). For SD_T1..SD_T4 it is where her hand holds it; for
// SD_GRIPS it is the same line inside the loose grip sprite, which is moved onto the frame's line at run time.
struct SdFrameInfo { int bbox[4]; float head[3]; int nTies; float ties[4][2]; float grip[4]; };
static const float kSdPivot[2] = { %.1ff, %.1ff };      // where the steering column leaves the ski body
static const float kSdExhaust[2] = { %.1ff, %.1ff };    // water jet outlet
static const SdFrameInfo kSdFrames[SD_FRAMES] = {
%s
};
''' % (', '.join(ENUM), CW, CH, piv[1], piv[0], ex[1], ex[0], '\n'.join(rows)))
print('ok', len(rows))
