#!/usr/bin/env python3
# Bakes the Wet-Rash art (layers exported from the PSDs by psd_export.py) into two atlases + a data header.
#   bake.py <exported png dir> <res dir> <header>
# colour atlas: 5x3 cells of 360x360.  mask atlas: R = bikini region, G = head (hair) region, B = tie marks.
import sys, numpy as np
from PIL import Image
from scipy import ndimage
src, res, hdr = sys.argv[1:4]
ORDER = ['ski-stop','ski-forward','ski-speed','ride','ride_low_for_speeding','lean_to_right_for_right_turn','look_to_the_right','punch_to_the_right','right_kick_to_the_right',
         'taunt1','hit1_from_the_right','hit2_from_right','fall1_to_the_right','fall2_to_the_right','swim_to_right']
ENUM = ['SKI_STOP','SKI_FWD','SKI_FAST','RIDE','TUCK','LEAN','LOOK','PUNCH','KICK','TAUNT','HIT1','HIT2','FALL1','FALL2','SWIM']
col = Image.new('RGBA', (1800, 1080), (0,0,0,0)); msk = Image.new('RGB', (1800, 1080), (0,0,0)); rows = []
def load(kind, n):
    try: return np.array(Image.open(f'{src}/{kind}__{n}.png').convert('RGBA'))
    except FileNotFoundError: return np.zeros((360,360,4), np.uint8)
for i, n in enumerate(ORDER):
    f = load('frames', n); ox, oy = (i % 5) * 360, (i // 5) * 360
    col.paste(Image.fromarray(f), (ox, oy))
    c, s, t = (load(k, n)[..., 3] > 0 for k in ('clothes', 'sculpts', 'ties'))
    m = np.zeros((360,360,3), np.uint8); m[..., 0] = c * 255; m[..., 1] = s * 255; m[..., 2] = t * 255
    msk.paste(Image.fromarray(m), (ox, oy))
    ys, xs = np.nonzero(f[..., 3]); bb = (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    head = (0, 0, 0)
    if s.any(): ys, xs = np.nonzero(s); head = (xs.mean(), ys.mean(), max(xs.max() - xs.min(), ys.max() - ys.min()) / 2 + 1)
    lab, k = ndimage.label(t); ties = [ndimage.center_of_mass(t, lab, j + 1) for j in range(k)][:4]
    pt = lambda a: (lambda yx: (float(yx[1].mean()), float(yx[0].mean())))(np.nonzero(a)) if a.any() else (0.0, 0.0)
    chest = (0, 0, 0, 0)                                  # upper bikini island: the part that gets secondary motion
    cl, ck = ndimage.label(c)
    if ck:
        tops = sorted(range(1, ck + 1), key=lambda j: ndimage.center_of_mass(c, cl, j)[0]); ys2, xs2 = np.nonzero(cl == tops[0])
        if len(ys2) > 40: chest = (xs2.min() - 3, ys2.min() - 3, xs2.max() + 4, ys2.max() + 4)
    jet = pt(load('waterjet', n)[..., 3] > 0); hnd = pt(load('steeringhandle', n)[..., 3] > 0)
    tie = ', '.join('{%.1ff, %.1ff}' % (x, y) for y, x in ties) or '{0, 0}'
    rows.append('    { {%d, %d, %d, %d}, {%.1ff, %.1ff, %.1ff}, %d, { %s }, {%.1ff, %.1ff}, {%.1ff, %.1ff}, {%d, %d, %d, %d} },   // %s' % (*bb, *head, len(ties), tie, *jet, *hnd, *chest, ENUM[i]))
col.save(f'{res}/atlas.png', optimize=True); msk.save(f'{res}/masks.png', optimize=True)
open(hdr, 'w').write('''// Generated by Tools/wetrash/bake.py from the artist's PSD layers. Do not edit.
#pragma once
enum WrFrame { %s, WR_FRAMES };
struct WrFrameInfo { int bbox[4]; float head[3]; int nTies; float ties[4][2]; float jet[2]; float handle[2]; int chest[4]; };   // all in 360x360 cell pixels
static const WrFrameInfo kWrFrames[WR_FRAMES] = {
%s
};
''' % (', '.join('WR_' + e for e in ENUM), '\n'.join(rows)))
print('ok', len(rows))
